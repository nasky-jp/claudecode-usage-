def to_yf_symbol(code: str) -> str:
    """東証コード → yfinance シンボル (8035 → 8035.T)。ETF等も同様。"""
    return f"{code}.T"


def match_sector(text: str) -> str | None:
    """自由文中のセクター表記を正規のセクター名に寄せる(表記ゆれ吸収)。"""
    t = text.strip()
    if t in JP_UNIVERSE:
        return t
    aliases = {
        "半導体関連": "半導体", "半導体製造装置": "半導体",
        "テクノロジー": "AI/テクノロジー", "AI": "AI/テクノロジー",
        "ハイテク": "AI/テクノロジー", "IT": "AI/テクノロジー",
        "石油": "エネルギー", "資源": "エネルギー",
        "銀行": "金融", "証券": "金融", "保険": "金融",
        "医薬品": "ヘルスケア", "製薬": "ヘルスケア", "医療": "ヘルスケア",
        "不動産": "不動産(REIT)", "REIT": "不動産(REIT)",
        "電力": "公共事業", "ガス": "公共事業", "電力・ガス": "公共事業",
        "化学": "素材", "鉄鋼": "素材", "非鉄": "素材", "非鉄金属": "素材",
        "食品": "生活必需品", "小売(必需品)": "生活必需品",
        "自動車": "一般消費財", "消費財": "一般消費財", "小売": "一般消費財",
        "情報通信": "通信", "通信キャリア": "通信",
        "機械": "資本財", "重工": "資本財", "産業機械": "資本財", "工業": "資本財",
    }
    if t in aliases:
        return aliases[t]
    for name in JP_UNIVERSE:
        if name in t or t in name:
            return name
    for alias, name in aliases.items():
        if alias in t:
            return name
    return None
